def _over(rgba, x, y, w, bg):
    i = (y * w + x) * 4
    a = rgba[i + 3] / 255.0
    return (int(round(rgba[i] * a + bg[0] * (1 - a))),
            int(round(rgba[i + 1] * a + bg[1] * (1 - a))),
            int(round(rgba[i + 2] * a + bg[2] * (1 - a))))


def _text(buf, W, H, x, y, text, colour, mag=1):
    cx = x
    for ch in text:
        glyph = _GLYPHS.get(ch, _GLYPHS[" "])
        for gy, row in enumerate(glyph):
            for gx, bit in enumerate(row):
                if bit != "1":
                    continue
                for sy in range(mag):
                    for sx in range(mag):
                        px, py = cx + gx * mag + sx, y + gy * mag + sy
                        if 0 <= px < W and 0 <= py < H:
                            di = (py * W + px) * 4
                            buf[di:di + 4] = bytes((*colour, 255))
        cx += 4 * mag


