def sheet(rows, path, title):
    """rows: list of (row label, [(page, offset, status, variant)])"""
    cell = 16 * SCALE
    gap, pad, cap = 6, 8, 22
    cols = len(rows[0][1])
    W = pad * 2 + cols * (cell + gap) - gap
    H = pad * 2 + len(rows) * (cell + cap + gap) - gap
    buf = bytearray(W * H * 4)
    for i in range(W * H):
        buf[i * 4:i * 4 + 4] = b"\x20\x22\x28\xff"
    idx = json.loads((OUT / "manifest.json").read_text())["items"]
    by = {(i["status"], i["variant"], i["offset"]): i for i in idx}
    findings = json.loads((REC / "findings.json").read_text())
    grades = {(i["status"], i["variant"], i["offset"]): i for i in findings["items"]}
    for ri, (label, cellspec) in enumerate(rows):
        for ci, (page, offset, status, variant) in enumerate(cellspec):
            it = by[(status, variant, offset)]
            w, h, rgba = pngio.read(OUT / it["png"])
            bgfn = measure.BACKDROPS[page]
            ox = pad + ci * (cell + gap)
            oy = pad + ri * (cell + cap + gap) + cap
            for y in range(h * SCALE):
                for x in range(w * SCALE):
                    sx, sy = x // SCALE, y // SCALE
                    bg = bgfn(ox + sx, oy + sy)
                    r, g, b = _over(rgba, sx, sy, w, bg)
                    di = ((oy + y) * W + ox + x) * 4
                    buf[di:di + 4] = bytes((r, g, b, 255))
            g = grades[(status, variant, offset)]["pages"][page]
            ink = g["core_contrast"]
            dec = g["decisive_contrast"]
            if dec is None:
                hole = g["slots"].get("hole", {})
                dec = hole.get("p75_contrast")
            _text(buf, W, H, ox, oy - cap + 2, f"{status[:4]} {page[:4]}", (200, 205, 215), 1)
            _text(buf, W, H, ox, oy - cap + 9, f"i{_n(ink)} d{_n(dec)}", (150, 220, 170), 1)
    _text(buf, W, H, pad, 1, title, (240, 242, 248), 1)
    pngio.write(path, W, H, bytes(buf))


def _n(v):
    if v is None:
        return "--"
    return f"{v:.1f}"


