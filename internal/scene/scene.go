// Package scene defines the portable prism-plate-v1 document contract.
package scene

import "prismplate/internal/geom"

type Color struct {
	R float64 `json:"r"`
	G float64 `json:"g"`
	B float64 `json:"b"`
	A float64 `json:"a"`
}
type Stop struct {
	At    float64 `json:"at"`
	Color Color   `json:"color"`
}

// MeshVertex carries one vertex color of a triangle mesh gradient.
type MeshVertex struct {
	X     float64 `json:"x"`
	Y     float64 `json:"y"`
	Color Color   `json:"color"`
}

// MeshTriangle indexes three mesh vertices; either winding is accepted.
type MeshTriangle struct {
	A int `json:"a"`
	B int `json:"b"`
	C int `json:"c"`
}

// Mesh is a vertex-color triangle grid. Triangles tile without interior
// overlap; the color function is barycentric interpolation in linear-light
// premultiplied space, transparent outside the union.
type Mesh struct {
	Vertices  []MeshVertex   `json:"vertices"`
	Triangles []MeshTriangle `json:"triangles"`
}
type Brush struct {
	Kind  string     `json:"kind"`
	Color Color      `json:"color"`
	From  geom.Point `json:"from"`
	To    geom.Point `json:"to"`
	Stops []Stop     `json:"stops,omitempty"`
	Mesh  *Mesh      `json:"mesh,omitempty"`
}
type Shape struct {
	ID        string      `json:"id"`
	Path      []geom.Op   `json:"path"`
	FillRule  string      `json:"fill_rule"`
	Brush     Brush       `json:"brush"`
	Transform geom.Matrix `json:"transform"`
}
type Layer struct {
	ID      string    `json:"id"`
	Opacity float64   `json:"opacity"`
	Blend   string    `json:"blend"`
	Clip    []geom.Op `json:"clip,omitempty"`
	Mask    []geom.Op `json:"mask,omitempty"`
	Shapes  []Shape   `json:"shapes"`
}
type Document struct {
	Width      int     `json:"width"`
	Height     int     `json:"height"`
	Background Color   `json:"background"`
	Layers     []Layer `json:"layers"`
}
type CompiledShape struct {
	Shape   Shape
	Path    geom.Path
	Inverse geom.Matrix
}
type CompiledLayer struct {
	Layer  Layer
	Clip   geom.Path
	Mask   geom.Path
	Shapes []CompiledShape
}
type Compiled struct {
	Document Document
	Layers   []CompiledLayer
	Segments int
}
